#!/usr/bin/env bash
# =============================================================================
# majlis-guard.sh · PreToolUse lane guard for Write/Edit
# -----------------------------------------------------------------------------
# The charter gives every member a sharp scope. This enforces the file-level
# part of it, because a prompt saying "you do NOT own the schema" is a request,
# not a control.
#
# Refuses, when the caller is a SUBAGENT (payload carries agent_type):
#   * .claude/agents/**   — member definitions. HR Lead's lane, and generated
#                           by install.py; an advisor editing one rewrites its
#                           own instructions.
#   * templates/**        — the boilerplate install.py renders from. Editing it
#                           silently changes every FUTURE install.
#   * Team's brain/<other>/ — another member's private working memory. The
#                           charter states brain folders are not an interface.
#
# Exit 0 allows. Exit 2 blocks and returns the reason to Claude.
# The main thread (no agent_type) is never restricted — the owner is trusted.
# =============================================================================
set -u

PAYLOAD="$(cat 2>/dev/null || true)"
[ -n "$PAYLOAD" ] || exit 0

json_str() {
  local key="$1"
  if command -v jq >/dev/null 2>&1; then
    printf '%s' "$PAYLOAD" | jq -r --arg k "$key" '.[$k] // .tool_input[$k] // empty' 2>/dev/null
  else
    printf '%s' "$PAYLOAD" \
      | sed -n "s/.*\"$key\"[[:space:]]*:[[:space:]]*\"\([^\"]*\)\".*/\1/p" | head -1
  fi
}

AGENT="$(json_str agent_type)"
FILE="$(json_str file_path)"

# Main thread, or nothing to inspect: allow.
[ -n "$AGENT" ] || exit 0
[ -n "$FILE" ] || exit 0

# Compare repo-relative.
ROOT="${CLAUDE_PROJECT_DIR:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"
REL="${FILE#"$ROOT"/}"

deny() { echo "BLOCKED by majlis-guard: $1" >&2; exit 2; }

case "$REL" in
  .claude/agents/*)
    # HR Lead designs and onboards members — that IS its lane.
    [ "$AGENT" = "hr-lead" ] && exit 0
    deny "'$AGENT' may not edit member definitions ($REL). Member files are generated by install.py and are HR Lead's lane." ;;
  templates/*)
    deny "'$AGENT' may not edit the install templates ($REL). Editing these changes every future install, not just this council." ;;
esac

case "$REL" in
  "Team's brain/"*)
    OWNER="${REL#Team\'s brain/}"; OWNER="${OWNER%%/*}"
    [ "$OWNER" = "$AGENT" ] && exit 0
    deny "'$AGENT' may not write to '$OWNER' working memory ($REL). Brain folders are private; hand off through Jarvis." ;;
esac

exit 0
